#!/usr/bin/env bash
# Deploys the whole QualityLink prototype to AWS (Stockholm, eu-north-1).
# Run it from AWS CloudShell inside the repo folder:   ./scripts/deploy.sh
#
# What it does:
#   1. Packages the Lambda code and uploads it to an S3 artifacts bucket
#   2. Creates/updates the CloudFormation stack from template.yaml
#   3. Writes frontend/js/config.js with the API URL and Cognito IDs
#   4. Uploads the website to the private S3 bucket and refreshes CloudFront
#   5. On the first deploy, loads the demo data and demo accounts
set -euo pipefail

STACK="qualitylink"
REGION="eu-north-1"
cd "$(dirname "$0")/.."

ACCOUNT=$(aws sts get-caller-identity --query Account --output text)
ARTIFACTS="qualitylink-artifacts-${ACCOUNT}-${REGION}"

echo "==> 1/5 Packaging Lambda code (bucket: ${ARTIFACTS})"
if ! aws s3api head-bucket --bucket "$ARTIFACTS" 2>/dev/null; then
  aws s3api create-bucket --bucket "$ARTIFACTS" --region "$REGION" \
    --create-bucket-configuration LocationConstraint="$REGION" >/dev/null
fi
aws cloudformation package --region "$REGION" \
  --template-file template.yaml --s3-bucket "$ARTIFACTS" \
  --output-template-file packaged.yaml >/dev/null

echo "==> 2/5 Deploying CloudFormation stack '${STACK}' (first time takes about 5 minutes)"
aws cloudformation deploy --region "$REGION" \
  --template-file packaged.yaml --stack-name "$STACK" \
  --capabilities CAPABILITY_IAM CAPABILITY_AUTO_EXPAND --no-fail-on-empty-changeset

out() {
  aws cloudformation describe-stacks --region "$REGION" --stack-name "$STACK" \
    --query "Stacks[0].Outputs[?OutputKey=='$1'].OutputValue" --output text
}
API_URL=$(out ApiUrl)
CLIENT_ID=$(out UserPoolClientId)
BUCKET=$(out SiteBucketName)
DIST_ID=$(out DistributionId)
SITE_URL=$(out WebsiteUrl)
SEED_FN=$(out SeedFunctionName)

echo "==> 3/5 Writing frontend config"
cat > frontend/js/config.js <<EOF
// Generated by scripts/deploy.sh. Do not edit by hand.
export const CONFIG = {
  region: "${REGION}",
  apiUrl: "${API_URL}",
  userPoolClientId: "${CLIENT_ID}",
  cognitoEndpoint: "https://cognito-idp.${REGION}.amazonaws.com/",
};
EOF

echo "==> 4/5 Uploading website and refreshing CloudFront"
aws s3 sync frontend "s3://${BUCKET}" --delete --region "$REGION" >/dev/null
aws cloudfront create-invalidation --distribution-id "$DIST_ID" --paths "/*" >/dev/null

echo "==> 5/5 Demo data"
COUNT=$(aws dynamodb scan --region "$REGION" --select COUNT --output text --query Count \
  --table-name "$(aws cloudformation describe-stack-resource --region "$REGION" --stack-name "$STACK" \
  --logical-resource-id BatchesTable --query StackResourceDetail.PhysicalResourceId --output text)")
if [ "$COUNT" = "0" ]; then
  aws lambda invoke --region "$REGION" --function-name "$SEED_FN" --payload '{}' \
    --cli-binary-format raw-in-base64-out /tmp/seed.json >/dev/null && cat /tmp/seed.json && echo
else
  echo "Data already loaded (run ./scripts/reset-demo.sh to reset it)"
fi

echo
echo "QualityLink is live: ${SITE_URL}"
echo "(A brand-new CloudFront site can take a few minutes before it loads.)"
